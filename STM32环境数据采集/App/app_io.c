#include <stdio.h>
#include "app_config.h"
#include "app_io.h"
#include "app_sched.h"

/**
 * @brief       扩展槽任务
 * @note        这里默认只做一件事: 开机 8 秒时打印一次任务运行统计,
 *              用来验证这个插槽确实被调度到了。你可以直接把它替换成自己的代码。
 */
void app_io_task(void)
{
    static uint8_t s_done = 0;

    if (s_done)
    {
        return;
    }

    s_done = 1;

    printf("\r\n[app_io] extension slot is running.\r\n");
    app_sched_dump();

    /* ==========================================================================================
     *                              下 面 是 可 以 直 接 抄 的 例 子
     * ==========================================================================================
     *
     * 例 1: 读 PC1 上的 MQ-2 燃气传感器 (ADC1/2)
     * ------------------------------------------------------------------------------------------
     *   static uint8_t s_init = 0;
     *
     *   if (!s_init)
     *   {
     *       // PC1 = ADC12_IN11, 配成模拟输入
     *       RCC->APB2ENR |= 1 << 4;                  // GPIOC 时钟
     *       sys_gpio_set(GPIOC, SYS_GPIO_PIN1, SYS_GPIO_MODE_AIN,
     *                    SYS_GPIO_OTYPE_PP, SYS_GPIO_SPEED_MID, SYS_GPIO_PUPD_NONE);
     *       adc_init();                              // 初始化 ADC1
     *       s_init = 1;
     *   }
     *   {
     *       uint32_t v = adc_get_result_average(11, 5);   // 通道 11, 取 5 次平均
     *       printf("MQ2 raw = %lu\r\n", (unsigned long)v);
     *   }
     *
     *   ★★★ 安全警告: MQ-2 是 5V 供电, 模拟输出可达 5V, 而 STM32 的 ADC 满量程只有 3.3V。
     *        必须先经 10k/20k 电阻分压 (输出 = 输入 x 20/(10+20) = 2/3) 再进 ADC,
     *        直接连会打坏 ADC 引脚! 分压点最好再并一个 100nF 电容滤高频。
     *
     * 例 2: 读 PG11 上的 DHT11 温湿度 (板载 U4 座, 直插免接线)
     * ------------------------------------------------------------------------------------------
     *   static uint8_t s_init = 0;
     *   uint8_t temp = 0, humi = 0;
     *
     *   if (!s_init) { dht11_init(); s_init = 1; }
     *   if (dht11_read_data(&temp, &humi) == 0)
     *   {
     *       printf("DHT11: %u C, %u %%RH\r\n", (unsigned)temp, (unsigned)humi);
     *   }
     *   // 注意: dht11_read_data() 内部有 ms 级延时, 一次约 5ms, 放在 500ms 周期的任务里没问题。
     *
     * 例 3: 用 PD11 驱动继电器 (切断燃气阀 / 开排风扇)
     * ------------------------------------------------------------------------------------------
     *   sys_gpio_set(GPIOD, SYS_GPIO_PIN11, SYS_GPIO_MODE_OUT,
     *                SYS_GPIO_OTYPE_PP, SYS_GPIO_SPEED_LOW, SYS_GPIO_PUPD_PD);
     *   sys_gpio_pin_set(GPIOD, SYS_GPIO_PIN11, 1);
     *
     *   ★★★ 安全警告: 继电器必须 三极管(或 MOSFET) + 续流二极管 + 光耦隔离,
     *        绝对不能直接挂 GPIO; 也不要从板子排针取电, 请外接电源只共地。
     *        更好的做法是把这段代码写进 app_alarm.c 的 app_alarm_actuator() 钩子里,
     *        那样就能自动跟着报警状态动作。
     *
     * 例 4: 用 PC6 输出 PWM 调光 / 调风扇转速 (TIM8_CH1, 无引脚冲突)
     * ------------------------------------------------------------------------------------------
     *   atim_timx_pwm_chy_init(1000 - 1, 72 - 1);    // 1kHz
     *   // 之后改 TIM8->CCR1 就能调占空比
     *
     * 例 5: 把数据通过 4G / WiFi 模块发出去 (板载 ATK-MODULE 座, PB10/PB11)
     * ------------------------------------------------------------------------------------------
     *   usart3_init(72, 115200);
     *   // 直接把 app_console.c 里那种 CSV 行拼成 AT 指令的载荷发出去即可
     * ==========================================================================================
     */
}
